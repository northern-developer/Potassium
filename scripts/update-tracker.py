#!/usr/bin/env python3
"""Regenerate each release's table of Epics and Tickets from plan/.

plan/<V.R>/ holds one file per Epic, E<nn>-<name>.md, starting
"# <V.R>:E<n>: <title>", and that Epic's Tickets in E<nn>/T<mm>-<name>.md,
starting "# <V.R>:E<n>.T<m>: <title>". Each file, and each Addendum
("### A<k>: <title>") inside one, has a "**Status:**" line beginning with
one of the status names below. The table sits between the plan markers in
plan/<V.R>/README.md. Don't edit it by hand.

Usage: update-tracker.py           rewrite every plan/<V.R>/README.md
       update-tracker.py --check   exit 1 if any is out of date or a file is malformed
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
PLAN = ROOT / "plan"
BEGIN = "<!-- plan:begin (generated by scripts/update-tracker.py) -->"
END = "<!-- plan:end -->"
STATUSES = ("Unassigned", "Assigned", "In progress", "Completed", "Dropped")


def fail(path, message):
    sys.exit(f"{path.relative_to(ROOT)}: {message}")


def read(path, expected):
    text = path.read_text()
    heading = re.match(r"# (\S+): (.+)", text)
    if not heading or heading.group(1) != expected:
        fail(path, f"needs a first line '# {expected}: <title>'")
    status = re.search(r"^\*\*Status:\*\* (.+)$", text, re.M)
    if not status or not status.group(1).startswith(STATUSES):
        fail(path, f"needs a '**Status:**' line starting with one of: {', '.join(STATUSES)}")
    for addendum in re.finditer(r"^### (A\d+): .+\n\n\*\*Status:\*\* (.+)$|^### (A\d+): .+$", text, re.M):
        if addendum.group(3) or not addendum.group(2).startswith(STATUSES):
            fail(path, f"Addendum {addendum.group(1) or addendum.group(3)} needs a valid '**Status:**' line")
    return heading.group(2).strip(), status.group(1).strip()


def number(path, prefix):
    match = re.match(rf"{prefix}(\d\d)-", path.name)
    if not match:
        fail(path, f"name must start with {prefix}<two digits>-")
    return int(match.group(1))


def render(release):
    vr = release.name
    rows = []
    for epic_path in sorted(release.glob("E[0-9][0-9]-*.md")):
        e = number(epic_path, "E")
        title, status = read(epic_path, f"{vr}:E{e}")
        rows.append(f"| **E{e}** | [{title}]({epic_path.name}) | {status} |")
        folder = release / f"E{e:02d}"
        for ticket_path in sorted(folder.glob("T[0-9][0-9]-*.md")):
            t = number(ticket_path, "T")
            title, status = read(ticket_path, f"{vr}:E{e}.T{t}")
            rows.append(f"| E{e}.T{t} | [{title}]({ticket_path.relative_to(release)}) | {status} |")
    return "\n".join([BEGIN, "| # | Epic / Ticket | Status |", "|---|---|---|", *rows, END])


def main():
    pattern = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.S)
    stale = []
    for release in sorted(p for p in PLAN.iterdir() if p.is_dir() and re.fullmatch(r"\d+\.\d+", p.name)):
        readme = release / "README.md"
        text = readme.read_text()
        if not pattern.search(text):
            fail(readme, "plan markers not found")
        updated = pattern.sub(lambda _: render(release), text)
        if updated != text:
            stale.append(readme)
            if "--check" not in sys.argv[1:]:
                readme.write_text(updated)
    if stale and "--check" in sys.argv[1:]:
        sys.exit("out of date: " + ", ".join(str(p.relative_to(ROOT)) for p in stale)
                 + " -- run scripts/update-tracker.py")


if __name__ == "__main__":
    main()
