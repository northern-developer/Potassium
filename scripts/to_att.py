#!/usr/bin/env python3
"""Write the AT&T-syntax twin of an Intel-syntax example.

usage: to_att.py <in.asm> <out.s> --ptasm <ptasm> --config <cpu.json>

tests/cmake/att_twins.cmake requires the twin to assemble to the same bytes. Two
cases the converter cannot spell:

* An Intel operand with no AT&T spelling (`[[R3 + 4]]`, `[[PC + 4]]`): the
  line becomes the `.BYTE` data the Intel line assembles to (read from
  `ptasm -l`).
* A line that ends in `-- AT&T: <line>` (or `; AT&T:`, `# AT&T:`) is
  replaced by that text, for an AT&T form with no Intel spelling (the scaled
  index `4(%R1, %R2, 2)`); the Intel file holds its bytes as `.BYTE`.
"""
import argparse
import re
import subprocess
import sys
import tempfile

BRANCHES = {"CALL", "JE", "JNE", "JMP"}
DIRECTIVE = re.compile(r"^\s*(?:[A-Za-z_][\w.]*:\s*)?\.", re.I)
CONSTANT = re.compile(r"^\s*[A-Za-z_][\w.]*\s+\.(?:EQU|SET)\b", re.I)
OVERRIDE = re.compile(r"(?:--|;|#)\s*AT&T:\s*(.*)$")


def split_comment(line):
    in_string = False
    for i, ch in enumerate(line):
        if ch == '"':
            in_string = not in_string
        elif not in_string:
            if ch in ";#":
                return line[:i], line[i:]
            if line.startswith("--", i):
                return line[:i], line[i:]
    return line, None


class Unspellable(Exception):
    pass


def operand(text, mnemonic):
    text = text.strip()
    if re.fullmatch(r"R\d+", text, re.I):
        return "%" + text
    if text.startswith("[["):
        raise Unspellable(text)
    m = re.fullmatch(r"\[\s*(?:RIP|PC)\s*([+-])\s*(.+?)\s*\]", text, re.I)
    if m:
        sign, disp = m.groups()
        return ("-" if sign == "-" else "") + disp + "(%RIP)"
    m = re.fullmatch(r"\[\s*(R\d+)\s*([+-])\s*(.+?)\s*\]", text, re.I)
    if m:
        reg, sign, disp = m.groups()
        return ("-" if sign == "-" else "") + disp + "(%" + reg + ")"
    m = re.fullmatch(r"\[\s*(R\d+)\s*\]", text, re.I)
    if m:
        return "(%" + m.group(1) + ")"
    m = re.fullmatch(r"\[\s*(.+?)\s*\]", text)
    if m:
        return m.group(1)
    return text if mnemonic in BRANCHES else "$" + text


def convert(code):
    m = re.match(r"(\s*)((?:[A-Za-z_][\w.]*:\s*)?)(.*)$", code)
    indent, label, rest = m.groups()
    rest_stripped = rest.strip()
    if not rest_stripped or rest_stripped.startswith(".") or CONSTANT.match(code):
        return code
    parts = rest_stripped.split(None, 1)
    mnemonic = parts[0]
    if len(parts) == 1:
        return indent + label + mnemonic
    operands = [operand(o, mnemonic.upper()) for o in parts[1].split(",")]
    trailing = rest[len(rest.rstrip()):]
    return indent + label + mnemonic + " " + ", ".join(reversed(operands)) + trailing


def listing_bytes(ptasm, config, source):
    """Source line number (1-based) -> the bytes `ptasm -l` shows for it."""
    with tempfile.TemporaryDirectory() as scratch:
        out = subprocess.run([ptasm, source, "-m", config, "-l", "-o", scratch + "/out.bin"], check=True,
                             capture_output=True, text=True).stdout.splitlines()
    lines = open(source, encoding="utf-8").read().splitlines()
    result = {}
    row = 0
    for number, text in enumerate(lines, 1):
        while row < len(out) and not out[row].rstrip().endswith(text.rstrip()):
            row += 1
        if row >= len(out):
            break
        prefix = out[row][: len(out[row].rstrip()) - len(text.rstrip())]
        found = re.findall(r"\b[0-9A-F]{2}\b", prefix[6:])
        if found:
            result[number] = found
        row += 1
    return result


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("source")
    parser.add_argument("target")
    parser.add_argument("--ptasm", required=True)
    parser.add_argument("--config", required=True)
    args = parser.parse_args()

    name = args.source.replace("\\", "/").rsplit("/", 1)[-1]
    out = [
        f"# AT&T-syntax twin of examples/{name} (E3.T1): the same program,",
        "# and ctest requires the same output in every format. Generated by",
        "# scripts/to_att.py; see that file for what it does and why.",
        "",
    ]
    bytes_of = None
    skipping_header = True
    for number, raw in enumerate(open(args.source, encoding="utf-8").read().splitlines(), 1):
        code, comment = split_comment(raw)
        if skipping_header and not code.strip():
            continue  # the Intel file's header comment block
        skipping_header = False
        if not code.strip() and comment is not None:
            continue  # explanations stay in the Intel file
        override = OVERRIDE.search(raw)
        if override:
            out.append(override.group(1).rstrip())
            continue
        try:
            line = convert(code)
        except Unspellable:
            if bytes_of is None:
                bytes_of = listing_bytes(args.ptasm, args.config, args.source)
            data = ", ".join("0x" + b for b in bytes_of[number])
            label = re.match(r"\s*((?:[A-Za-z_][\w.]*:\s*)?)", code).group(1)
            line = f"{label}.BYTE {data}"
            comment = "no AT&T spelling for: " + code.strip()
        if comment is not None:
            line = line.rstrip() + " # " + comment.lstrip("-;# ").rstrip()
        out.append(line.rstrip())
    open(args.target, "w", encoding="utf-8").write("\n".join(out) + "\n")


if __name__ == "__main__":
    sys.exit(main())
